#!/usr/bin/env python3
"""Compose the UBC study's pages from shared partials.

Three pages share a nav, a footer and a stylesheet. Copy-pasting that chrome
into each page is how a nav ends up disagreeing with itself two edits from now,
so it lives in partials/ and is written in exactly once, here.

    python3 build.py           # build
    python3 build.py --check   # fail if any built page is stale (for CI/pre-deploy)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).parent
HEAD = (ROOT / "partials/head.html").read_text()
TOP = (ROOT / "partials/chrome-top.html").read_text()
BOTTOM = (ROOT / "partials/chrome-bottom.html").read_text()

BANNER = "<!-- Built by build.py from partials/ + pages/. Do not edit this file directly. -->"

# page key -> (output file, body file, <title>, meta description, nav key to mark current)
PAGES = {
    "index": (
        "index.html", "pages/index.body.html",
        "Universal Ballet Competition — The World Stage, at Student Age",
        "The world's top student ballet competition. Master classes, scholarships "
        "and international opportunities for young dancers. 16 cities, 2026–2027 season.",
        "season",
    ),
    "rules": (
        "rules.html", "pages/rules.body.html",
        "Rules & Regulations — Universal Ballet Competition",
        "Age divisions, competition levels, categories, time limits, fees and "
        "adjudicated scoring for the UBC 2026–2027 season.",
        "compete",
    ),
    "judges": (
        "judges.html", "pages/judges.body.html",
        "Judges — Universal Ballet Competition",
        "The dancers, company directors and ballet school directors who adjudicate "
        "and teach at Universal Ballet Competition.",
        "judges",
    ),
}


def compose(title, description, body, nav_key, depth_prefix=""):
    head = HEAD
    head = re.sub(r"<title>.*?</title>", f"<title>{title}</title>", head, flags=re.S)
    head = re.sub(
        r'<meta name="description" content=".*?">',
        f'<meta name="description" content="{description}">',
        head, flags=re.S,
    )
    top = TOP
    # mark the current section in the nav, so every page says where you are
    if nav_key:
        top = top.replace(f'data-nav="{nav_key}"', f'data-nav="{nav_key}" aria-current="page"')
    return (
        "<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n"
        f"{BANNER}\n{head}</head>\n<body>\n{top}\n{body}\n{BOTTOM}\n"
    )


def build(check=False):
    stale, written = [], []
    for key, (out, body_file, title, desc, nav) in PAGES.items():
        body = (ROOT / body_file).read_text().rstrip() + "\n"
        html = compose(title, desc, body, nav)
        target = ROOT / out
        current = target.read_text() if target.exists() else None
        if current == html:
            continue
        if check:
            stale.append(out)
        else:
            target.write_text(html)
            written.append(f"{out} ({len(html):,} bytes)")

    if check:
        if stale:
            print("STALE, rebuild needed: " + ", ".join(stale))
            return 1
        print(f"all {len(PAGES)} pages current")
        return 0

    for w in written:
        print("wrote", w)
    if not written:
        print("no changes")

    # Chrome must be byte-identical everywhere — that is the whole point of partials.
    bodies = {p[0]: (ROOT / p[0]).read_text() for p in PAGES.values()}
    for name, html in bodies.items():
        assert TOP.split("\n")[0] in html, f"{name} lost the chrome"
        assert '<link rel="stylesheet" href="assets/ubc.css">' in html, f"{name} lost the stylesheet"
    nav_counts = {n: h.count('class="menu"') for n, h in bodies.items()}
    assert len(set(nav_counts.values())) == 1, f"nav differs between pages: {nav_counts}"
    print(f"chrome identical across {len(bodies)} pages")
    return 0


if __name__ == "__main__":
    sys.exit(build(check="--check" in sys.argv))
